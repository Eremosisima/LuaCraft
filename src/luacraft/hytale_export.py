"""Hytale asset pack exporter.

Hytale modding is split in two halves: Java plugins (compiled, out of scope
here) and *asset packs*, which are plain JSON plus model and texture files.
This module renders the declared LuaCraft content into the asset pack layout:

``manifest.json``
    Pack metadata.
``Server/Item/Items/*.json``
    Item definitions.
``Server/Item/Recipes/*.json``
    Crafting recipes.
``Server/NPC/Roles/*.json``
    NPC roles that reference a server model.
``Server/Models/*.json``
    Server model descriptions (model, texture, hitbox, eye height).
``Server/Drops/*.json``
    Drop tables with the recursive ``Container`` schema.
``Common/NPC/<Name>/Model.blockymodel``
    Converted geometry, 32 units per block.
``Common/NPC/<Name>/Texture.png``
    Entity texture.
``Common/Icons/ItemsGenerated/*.png``
    Item icons.
``Server/Lang/en-US.json``
    Localisation keys used by the item and role definitions.

What this cannot do is stated as a diagnostic instead of being silently
dropped: Bedrock/Molang animation controllers, script APIs, spawning rules
beyond a simple drop table, and Java gameplay logic have no asset pack
equivalent.  The generated pack is schema-valid and installable, and the
report lists every approximated field.

Everything is offline and standard library only.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from typing import Any

from .content import Content, EntityDef, ItemDef, RecipeDef
from .diagnostics import Category, DiagnosticBag
from .textures import TextureSet, texture_names

#: The default Hytale version the generated manifest declares.
DEFAULT_SERVER_VERSION = "2026.01.13"


def _json(payload: Any) -> str:
    """Render deterministic JSON: stable key order, two space indent."""
    return json.dumps(payload, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def _asset_name(value: str) -> str:
    """Turn an identifier into a Hytale asset name."""
    name = value.split(":", 1)[-1]
    cleaned = "".join(
        character if character.isalnum() or character in "-_" else "_"
        for character in name
    )
    return cleaned.strip("_") or "asset"


@dataclass
class HytalePack:
    """Renders a Hytale asset pack from intermediate content."""

    namespace: str = "luacraft"
    pack_name: str = "LuaCraft"
    description: str = "Generated by LuaCraft"
    server_version: str = DEFAULT_SERVER_VERSION
    #: Pre-rendered ``.blockymodel`` documents keyed by entity name.
    blockymodels: dict[str, dict[str, Any]] = field(default_factory=dict)
    #: Human readable fidelity notes, exposed through ``report``.
    notes: list[str] = field(default_factory=list)

    def __post_init__(self) -> None:
        self.diagnostics = DiagnosticBag()

    # -- public -----------------------------------------------------------

    def build(
        self, content: Content, textures: TextureSet | None = None
    ) -> dict[str, bytes | str]:
        """Render the whole pack as ``path -> bytes or text``."""
        files: dict[str, bytes | str] = {}
        files["manifest.json"] = _json(self._manifest())

        entity_ids = {entity.identifier for entity in content.entities.values()}
        recipes_by_result: dict[str, list[RecipeDef]] = {}
        for recipe in content.recipes.values():
            recipes_by_result.setdefault(recipe.result, []).append(recipe)

        for item in content.items.values():
            if item.fallback_for and item.fallback_for in entity_ids:
                # Hytale has real NPCs, so a species card is redundant.
                continue
            name = _asset_name(item.name)
            files[f"Server/Item/Items/{name}.json"] = _json(
                self._item(item, recipes_by_result.get(item.identifier, []))
            )

        for recipe in content.recipes.values():
            name = _asset_name(recipe.name)
            files[f"Server/Item/Recipes/{name}.json"] = _json(self._recipe(recipe))

        lang: dict[str, str] = {}
        for item in content.items.values():
            if item.fallback_for and item.fallback_for in entity_ids:
                continue
            name = _asset_name(item.name)
            lang[f"items.{self.namespace}.{name}.name"] = (
                item.display_name or item.name
            )

        used_blockymodels: set[str] = set()
        for name, entity in content.entities.items():
            asset = _asset_name(name)
            files[f"Server/NPC/Roles/{asset}.json"] = _json(
                self._npc_role(entity, asset)
            )
            files[f"Server/Models/{asset}.json"] = _json(self._server_model(entity, asset))
            if entity.drops:
                files[f"Server/Drops/{asset}_drops.json"] = _json(
                    self._drops(entity)
                )
            key = next(
                (
                    candidate
                    for candidate in (entity.model, name, asset)
                    if candidate and candidate in self.blockymodels
                ),
                None,
            )
            if key is not None:
                files[f"Common/NPC/{asset}/Model.blockymodel"] = _json(
                    self.blockymodels[key]
                )
                used_blockymodels.add(key)
                self.notes.append(
                    f"{name}: geometry exported as {asset}/Model.blockymodel in "
                    "32 units per block"
                )
            lang[f"npcs.{self.namespace}.{asset}.name"] = (
                entity.display_name or entity.name
            )

        for name, document in self.blockymodels.items():
            if name in used_blockymodels:
                continue
            asset = _asset_name(name)
            path = f"Common/NPC/{asset}/Model.blockymodel"
            if path in files:
                continue
            files[path] = _json(document)
            self.notes.append(
                f"{name}: geometry exported as {asset}/Model.blockymodel in "
                "32 units per block"
            )

        if textures is not None:
            for texture in texture_names(content):
                png = textures.for_name(texture)
                files[f"Common/Icons/ItemsGenerated/{texture}.png"] = png
                files[f"Common/NPC/{texture}/Texture.png"] = png
            for entity in content.entities.values():
                png = textures.for_name(
                    entity.texture or entity.model or entity.name
                )
                files[f"Common/NPC/{_asset_name(entity.name)}/Texture.png"] = png

        if lang:
            files["Server/Lang/en-US.json"] = _json(lang)

        self._warn_limits(content)
        return files

    def report(self, content: Content) -> dict[str, Any]:
        """A JSON-friendly description of what the pack contains."""
        return {
            "target": "hytale-asset-pack",
            "pack_name": self.pack_name,
            "server_version": self.server_version,
            "counts": {
                "items": sum(
                    1
                    for item in content.items.values()
                    if not (
                        item.fallback_for
                        and item.fallback_for
                        in {e.identifier for e in content.entities.values()}
                    )
                ),
                "entities": len(content.entities),
                "blockymodels": len(self.blockymodels),
                "recipes": len(content.recipes),
                "drops": sum(1 for entity in content.entities.values() if entity.drops),
            },
            "notes": list(self.notes),
            "limitations": [
                "Java plugin logic is not generated; only JSON asset packs.",
                "Molang animations are not converted: models are static.",
                "Bedrock spawn rules become a single default drop-free role.",
                "Field names follow the public 2026 Hytale asset documentation; "
                "verify them against the installed game version.",
            ],
        }

    # -- documents --------------------------------------------------------

    def _manifest(self) -> dict[str, Any]:
        return {
            "Group": "LuaCraft",
            "Name": self.pack_name,
            "Version": "1.0.0",
            "Description": self.description,
            "Authors": [{"Name": "LuaCraft"}],
            "ServerVersion": self.server_version,
            "Dependencies": {},
            "OptionalDependencies": {},
            "DisabledByDefault": False,
            "IncludesAssetPack": True,
        }

    def _item(self, item: ItemDef, recipes: list[RecipeDef]) -> dict[str, Any]:
        document: dict[str, Any] = {
            "TranslationProperties": {
                "Name": f"items.{self.namespace}.{_asset_name(item.name)}.name"
            },
            "Categories": [item.category or "Items"],
            "MaxStack": item.max_stack if item.max_stack is not None else 100,
            "Icon": (
                f"Icons/ItemsGenerated/{item.texture or _asset_name(item.name)}.png"
            ),
        }
        if item.durability is not None:
            document["MaxDurability"] = item.durability
        if item.food is not None:
            document["Consumable"] = True
            document["Consume"] = {
                "Health": float(item.food.get("nutrition", 0) or 0),
                "Time": 1.0,
            }
        if recipes:
            document["Recipe"] = f"Recipes/{_asset_name(recipes[0].name)}"
        return document

    def _recipe(self, recipe: RecipeDef) -> dict[str, Any]:
        inputs = [
            {"Item": ingredient, "Quantity": 1} for ingredient in recipe.ingredients
        ]
        if recipe.type == "shaped":
            # A shaped recipe keeps its pattern as a comment so the shape is
            # not lost even though the schema below is order based.
            document: dict[str, Any] = {
                "Type": "Crafting",
                "Input": inputs,
                "Output": {"Item": recipe.result, "Quantity": recipe.count},
                "Bench": "Workbench",
                "Pattern": list(recipe.pattern),
            }
        else:
            document = {
                "Type": "Crafting",
                "Input": inputs,
                "Output": {"Item": recipe.result, "Quantity": recipe.count},
                "Bench": "Workbench",
            }
        return document

    def _npc_role(self, entity: EntityDef, asset: str) -> dict[str, Any]:
        role: dict[str, Any] = {
            "Type": "Generic",
            "Name": f"npcs.{self.namespace}.{asset}.name",
            "Appearance": f"Models/{asset}.json",
            "Stats": {
                "Health": float(entity.health if entity.health is not None else 20.0),
                "MovementSpeed": float(
                    entity.movement_speed
                    if entity.movement_speed is not None
                    else 0.2
                ),
            },
            "HitBox": {"Width": entity.width, "Height": entity.height},
        }
        if entity.hostile:
            role["Hostile"] = True
        if entity.tameable:
            role["Tameable"] = {
                "Items": list(entity.tameable.get("tame_items", [])),
                "Chance": float(entity.tameable.get("probability", 1.0)),
            }
        if entity.drops:
            role["Drops"] = {"DropTable": f"Drops/{asset}_drops.json"}
        if entity.families:
            role["Tags"] = list(entity.families)
        return role

    def _server_model(self, entity: EntityDef, asset: str) -> dict[str, Any]:
        return {
            "Model": f"NPC/{asset}/Model.blockymodel",
            "Texture": f"NPC/{asset}/Texture.png",
            "EyeHeight": round(entity.height * 0.85, 3),
            "HitBox": {"Width": entity.width, "Height": entity.height},
            "AnimationSets": [],
        }

    def _drops(self, entity: EntityDef) -> dict[str, Any]:
        entries: list[dict[str, Any]] = []
        for drop in entity.drops:
            single = {
                "Type": "Single",
                "Item": drop["item"],
                "Quantity": {
                    "Min": int(drop.get("min", 1)),
                    "Max": int(drop.get("max", 1)),
                },
            }
            chance = float(drop.get("chance", 1.0))
            if chance >= 1.0:
                entries.append(single)
                continue
            entries.append(
                {
                    "Type": "Choice",
                    "Entries": [
                        {
                            "Type": "Single",
                            "Item": drop["item"],
                            "Quantity": single["Quantity"],
                            "Weight": max(1, int(round(chance * 100))),
                        },
                        {
                            "Type": "Empty",
                            "Weight": max(1, int(round((1.0 - chance) * 100))),
                        },
                    ],
                }
            )
        return {"Container": {"Type": "Multiple", "Entries": entries}}

    # -- diagnostics ------------------------------------------------------

    def _warn_limits(self, content: Content) -> None:
        if content.entities:
            self.diagnostics.warn(
                Category.PARTIAL_SUPPORT,
                (
                    "Hytale asset packs cannot carry gameplay code. The NPC roles "
                    "define appearance, stats, hitbox, taming and drops; AI, "
                    "animations and interactions need a Java plugin"
                ),
                0,
                edition="hytale",
                hint="write a Java plugin against the installed Hytale server API",
            )
        for entity in content.entities.values():
            if entity.unsupported:
                self.diagnostics.warn(
                    Category.PARTIAL_SUPPORT,
                    (
                        f"{entity.identifier}: not representable in a Hytale asset "
                        "pack: " + ", ".join(sorted(entity.unsupported))
                    ),
                    entity.line,
                    symbol=entity.identifier,
                    edition="hytale",
                )
            if entity.name not in self.blockymodels and (
                entity.model or ""
            ) not in self.blockymodels:
                self.diagnostics.warn(
                    Category.PARTIAL_SUPPORT,
                    (
                        f"{entity.identifier}: no geometry was converted, so the "
                        "role points at a model file the pack does not contain"
                    ),
                    entity.line,
                    symbol=entity.identifier,
                    edition="hytale",
                    hint="pass --model-dir or convert the pack with tools/convert_bedrock.py",
                )
        if any(recipe.type == "shaped" for recipe in content.recipes.values()):
            self.diagnostics.warn(
                Category.PARTIAL_SUPPORT,
                (
                    "shaped recipes are exported with their pattern recorded, but "
                    "the Hytale crafting schema is order based; the layout may need "
                    "manual adjustment"
                ),
                0,
                edition="hytale",
            )
