"""The Bedrock Edition backend.

Turns a Lua source into a Bedrock add-on: a behaviour pack, a resource pack and
the Script API module that implements the logic.

Where Java Edition uses mcfunctions, Bedrock uses the ``@minecraft/server``
module, so the generated code is TypeScript that the game compiles itself.

Structure of the generated add-on::

    <ns>_bp/manifest.json
    <ns>_bp/scripts/main.ts       the compiled logic
    <ns>_bp/functions/main.mcfunction  the commands Bedrock can run directly
    <ns>_rp/manifest.json
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Iterable

from .api import Edition
from .diagnostics import DiagnosticBag
from .java_backend import BackendResult
from .luaparse import (
    Assign,
    Call,
    Chunk,
    Comparison,
    ExprStat,
    Function,
    FunctionBody,
    If,
    Index,
    LocalAssign,
    LogicalOp,
    Name,
    Node,
    Number,
    String,
    Table,
    TrueLit,
    FalseLit,
)


#: Minecraft version the generated packs declare support for.
DEFAULT_BEDROCK_VERSION = (1, 21, 0)

#: Names imported from `@minecraft/server`.
SCRIPT_API_SYMBOLS = (
    "world",
    "system",
    "scoreboard",
    "ObjectiveCriteria",
    "ItemStack",
    "Vector3",
    "Dimension",
)


@dataclass
class BedrockBackend:
    """Compiles Lua into a Bedrock Edition add-on."""

    namespace: str = "luacraft"
    pack_name: str = "LuaCraft Mod"
    pack_description: str = "Generated by LuaCraft"
    min_engine_version: tuple[int, int, int] = field(
        default=DEFAULT_BEDROCK_VERSION
    )
    edition = Edition.BEDROCK

    def __post_init__(self) -> None:
        self.diagnostics = DiagnosticBag()
        self._body: list[str] = []
        self._objectives: list[str] = []
        self._used: set[str] = set()
        #: Name of the loop variable that holds the current player while an
        #: iteration body is being emitted.
        self._player_binding: str | None = None
        #: Name of the loop variable that holds the current entity.
        self._entity_binding: str | None = None

    # -- public -----------------------------------------------------------

    def compile(self, chunk: Chunk) -> BackendResult:
        """Compile a parsed chunk into an add-on."""
        self._body = []
        self._objectives = []
        self._used = set()

        for statement in chunk.body:
            self._emit_statement(statement, self._body)

        result = BackendResult(edition=Edition.BEDROCK)
        result.objectives = [(name, "dummy") for name in self._objectives]

        result.add("bp/manifest.json", self._manifest("behavior_pack"))
        result.add("rp/manifest.json", self._manifest("resource_pack"))
        result.add("bp/scripts/main.ts", self._script())
        result.add("bp/functions/main.mcfunction", self._mcfunction())
        return result

    # -- manifests --------------------------------------------------------

    def _manifest(self, pack_type: str) -> str:
        uuid = _deterministic_uuid(f"{self.namespace}:{pack_type}")
        module_uuid = _deterministic_uuid(f"{self.namespace}:{pack_type}:module")
        version = ", ".join(str(n) for n in self.min_engine_version)
        if pack_type == "behavior_pack":
            description = "LuaCraft behaviour pack"
            module_type = "data"
        else:
            description = "LuaCraft resource pack"
            module_type = "resources"
        return (
            "{\n"
            '  "format_version": 2,\n'
            '  "header": {\n'
            f'    "name": "{self.pack_name} ({pack_type})",\n'
            f'    "description": "{description}",\n'
            f'    "uuid": "{uuid}",\n'
            f'    "version": [{version}],\n'
            f'    "min_engine_version": [{version}]\n'
            "  },\n"
            '  "modules": [\n'
            "    {\n"
            f'      "description": "{description}",\n'
            f'      "type": "{module_type}",\n'
            f'      "uuid": "{module_uuid}"\n'
            "    }\n"
            "  ]\n"
            "}\n"
        )

    # -- script generation ------------------------------------------------

    def _script(self) -> str:
        lines: list[str] = []
        for objective in self._objectives:
            self._used.add("scoreboard")
            self._used.add("ObjectiveCriteria")
            lines.append(
                f"scoreboard.addObjective({_ts_string(objective)}, "
                "ObjectiveCriteria.Dummy);"
            )
        if self._objectives:
            lines.append("")

        lines.extend(self._body)

        header = ""
        if self._used:
            ordered = [s for s in SCRIPT_API_SYMBOLS if s in self._used]
            header = (
                f'import {{ {", ".join(ordered)} }} from "@minecraft/server";\n'
            )
        if not lines:
            lines.append("// LuaCraft generated an empty script.")
        return header + "\n" + "\n".join(lines) + "\n"

    def _mcfunction(self) -> str:
        """The mcfunction variant, for the commands Bedrock can run directly."""
        return "\n".join(self._body) + "\n"

    # -- statement handling ----------------------------------------------

    def _emit_statement(self, node: Node, out: list[str]) -> None:
        if isinstance(node, ExprStat):
            self._emit_call(node.expression, out)
            return
        if isinstance(node, If):
            self._emit_if(node, out)
            return
        if isinstance(node, Assign):
            target = node.targets[0]
            if isinstance(target, Index):
                # `items.ruby = { ... }` declares content, not logic.
                return
            value = node.values[0] if node.values else None
            if isinstance(value, Call):
                self._emit_call(value, out)
            return
        return

    def _emit_if(self, node: If, out: list[str]) -> None:
        """Emit an `if` statement as a TypeScript conditional."""
        for condition, body in node.branches:
            expression = self._condition_expression(condition)
            if expression is None:
                continue
            inner = self._body_lines(body)
            out.append(f"if ({expression}) {{")
            out.extend(f"  {line}" for line in inner)
            out.append("}")
        if node.else_body:
            inner = self._body_lines(node.else_body)
            out.append("else {")
            out.extend(f"  {line}" for line in inner)
            out.append("}")

    def _body_lines(self, body: list[Node]) -> list[str]:
        buffer: list[str] = []
        for statement in body:
            self._emit_statement(statement, buffer)
        return buffer

    def _condition_expression(self, condition: Node) -> str | None:
        """Translate a Lua condition into a TypeScript expression."""
        comparison: Comparison | None = None
        if isinstance(condition, Comparison):
            comparison = condition
        elif isinstance(condition, LogicalOp) and condition.op == "and":
            for part in (condition.left, condition.right):
                if isinstance(part, Comparison):
                    comparison = part
                    break
        if comparison is None:
            return None
        if comparison.op not in (">=", ">", "<=", "<", "==", "~="):
            return None
        if not isinstance(comparison.left, Call):
            return None
        if not isinstance(comparison.left.func, Name):
            return None
        if comparison.left.func.identifier != "score":
            return None
        args = comparison.left.args
        if len(args) < 2:
            return None
        self._used.add("scoreboard")
        objective = _ts_string(_plain(args[1]))
        value = _ts_literal(comparison.right)
        operator = {
            ">=": ">=", ">": ">", "<=": "<=", "<": "<",
            "==": "==", "~=": "!=",
        }[comparison.op]
        return f"scoreboard.getScore({objective}).value {operator} {value}"

    def _emit_call(self, node: Node, out: list[str]) -> None:
        if not isinstance(node, Call):
            return
        if node.method or not isinstance(node.func, Name):
            return
        name = node.func.identifier

        if name == "onTick":
            self._used.add("system")
            out.append("system.runInterval(() => {")
            callback = node.args[0] if node.args else None
            if isinstance(callback, Function):
                out.extend(f"  {line}" for line in self._body_lines(callback.body.body))
            out.append("}, 1);")
            return
        if name in ("onJoin", "onLoad"):
            self._used.add("world")
            out.append("world.afterEvents.playerSpawn.subscribe((event) => {")
            callback = node.args[0] if node.args else None
            if isinstance(callback, Function):
                out.extend(f"  {line}" for line in self._body_lines(callback.body.body))
            out.append("});")
            return
        if name == "onBedrockOnly":
            callback = node.args[0] if node.args else None
            if isinstance(callback, Function):
                out.extend(self._body_lines(callback.body.body))
            return
        if name == "onJavaOnly":
            # Dropped from the Bedrock build.
            return

        expression = self._expression_for(name, node)
        if expression:
            out.append(expression)

    # -- expression construction ------------------------------------------

    def _expression_for(self, name: str, node: Call) -> str:
        args = node.args

        def arg(index: int, default: str = '""') -> str:
            """Fetch an argument, tolerating a short argument list.

            The analyser has already reported an unavailable capability, so
            the backend must not crash on the same source.
            """
            if index < len(args):
                return _ts_literal(args[index])
            return default

        def plain_arg(index: int, default: str = "") -> str:
            if index < len(args):
                return _plain(args[index])
            return default

        if name == "say":
            self._used.add("world")
            return f"world.sendMessage({arg(0)});"
        if name == "message":
            player = _ts_player(args[0], self._player_binding) if args else 'world.getEntity("player")'
            return f"{player}.sendMessage({arg(1)});"
        if name == "give":
            player = _ts_player(args[0], self._player_binding) if args else 'world.getEntity("player")'
            self._used.add("ItemStack")
            count = arg(2, "1")
            return (
                f"{player}.getInventory().addItem(new ItemStack({arg(1)}, {count}));"
            )
        if name == "clear":
            player = _ts_player(args[0], self._player_binding) if args else 'world.getEntity("player")'
            if len(args) > 1:
                return f"{player}.getInventory().removeItem({arg(1)});"
            return f"{player}.getInventory().clear();"
        if name == "score":
            self._used.add("scoreboard")
            objective = arg(1)
            if len(args) == 2:
                return f"scoreboard.getScore({objective}).value;"
            operation = plain_arg(2, "set")
            value = arg(3, "1")
            operator = {
                "set": "=",
                "add": "+=",
                "remove": "-=",
                "subtract": "-=",
            }.get(operation, "=")
            return f"scoreboard.getScore({objective}).value {operator} {value};"
        if name == "addObjective":
            self._used.add("scoreboard")
            self._used.add("ObjectiveCriteria")
            self._objectives.append(plain_arg(0))
            return ""
        if name == "effect":
            player = _ts_player(args[0], self._player_binding) if args else 'world.getEntity("player")'
            seconds = arg(2, "30")
            amplifier = arg(3, "0")
            return (
                f"{player}.addEffect({arg(1)}, {seconds}, "
                f"{{ amplifier: {amplifier} }});"
            )
        if name == "playSound":
            sound = arg(0)
            if len(args) > 1:
                player = _ts_player(args[1], self._player_binding)
                return f"{player}.playSound({sound});"
            self._used.add("world")
            return f"world.playSound({sound});"
        if name == "teleport":
            player = _ts_player(args[0], self._player_binding) if args else 'world.getEntity("player")'
            self._used.add("Vector3")
            return f"{player}.teleport(new Vector3({arg(1)}, {arg(2)}, {arg(3)}));"
        if name == "runCommand":
            self._used.add("world")
            return f"world.runCommand({arg(0)});"
        if name == "setblock":
            self._used.add("world")
            return (
                f"world.runCommand(`setblock {arg(1)} {arg(2)} {arg(3)} {arg(4)}`);"
            )
        if name == "forEachPlayer":
            self._used.add("world")
            callback = args[0] if args else None
            saved = self._player_binding
            self._player_binding = "player"
            try:
                body = self._callback_body(callback)
            finally:
                self._player_binding = saved
            return f"for (const player of world.getAllPlayers()) {{ {body} }}"
        if name == "forEachEntity":
            self._used.add("world")
            entity_type = arg(0)
            callback = args[1] if len(args) > 1 else None
            saved = self._entity_binding
            self._entity_binding = "entity"
            try:
                body = self._callback_body(callback)
            finally:
                self._entity_binding = saved
            return (
                "for (const entity of world.getDimension(\"overworld\")"
                f".getEntities({entity_type})) {{ {body} }}"
            )
        if name == "setDynamicProperty":
            self._used.add("world")
            return f"{_ts_player(args[0], self._player_binding) if args else 'target'}.setDynamicProperty({arg(1)}, {arg(2)});"
        if name == "getDynamicProperty":
            self._used.add("world")
            return f"{_ts_player(args[0], self._player_binding) if args else 'target'}.getDynamicProperty({arg(1)});"
        if name == "nbt":
            # Java only: emit a placeholder so the script stays valid.
            return "// nbt() has no Bedrock equivalent"
        return ""

    def _callback_body(self, callback: Node | None) -> str:
        """Render a callback function as the body of a JavaScript block."""
        if not isinstance(callback, Function):
            return "/* empty */"
        lines = self._body_lines(callback.body.body)
        if not lines:
            return "/* empty */"
        return " ".join(lines)


# --------------------------------------------------------------------------
# Helpers
# --------------------------------------------------------------------------


def _ts_literal(node: Node) -> str:
    """Render a Lua literal as a TypeScript expression."""
    if isinstance(node, String):
        return _ts_string(node.value)
    if isinstance(node, Number):
        return str(node.value)
    if isinstance(node, TrueLit):
        return "true"
    if isinstance(node, FalseLit):
        return "false"
    if isinstance(node, Name):
        return _ts_string(node.identifier)
    return '""'


def _ts_string(value: str) -> str:
    escaped = (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\t", "\\t")
    )
    return f'"{escaped}"'


def _ts_player(node: Node, binding: str | None = None) -> str:
    """Render a player reference as a TypeScript expression.

    When the reference happens to be the loop variable of an enclosing
    iteration, the binding is used instead of looking the player up again.
    """
    if isinstance(node, Name):
        if binding and node.identifier in ("player", "self", "s", "target"):
            return binding
        return f'world.getEntity("{node.identifier}")'
    return 'world.getEntity("player")'


def _plain(node: Node) -> str:
    if isinstance(node, String):
        return node.value
    if isinstance(node, Name):
        return node.identifier
    if isinstance(node, Number):
        return str(node.value)
    return ""


def _deterministic_uuid(seed: str) -> str:
    """Build a stable UUID from a string, so builds are reproducible."""
    import hashlib

    digest = hashlib.sha256(seed.encode("utf-8")).hexdigest()
    return (
        f"{digest[0:8]}-{digest[8:12]}-{digest[12:16]}-"
        f"{digest[16:20]}-{digest[20:32]}"
    )
