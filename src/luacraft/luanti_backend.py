"""The Luanti backend.

Luanti (formerly Minetest) is the most natural target for LuaCraft: its mods
are written in Lua, so the author's own callbacks survive the compilation
almost unchanged.  Only the primitive calls are rewritten into Luanti's
``core`` API.

The generated mod has the standard Luanti layout::

    <mod>/init.lua        the compiled logic and the content registrations
    <mod>/mod.conf        name, description and dependencies
    <mod>/textures/       where the textures are expected to live

Two things differ from the other backends and are worth knowing about.

Identifiers
    Luanti uses ``modname:itemname``.  The namespace of the pack is the name
    of the mod, so an identifier such as ``luacraft:ruby`` is valid only
    when the mod is called ``luacraft``.  The backend renames the namespace
    when it does not match the mod name.

Scores
    Luanti has no scoreboard.  Scores are kept in the player metadata
    instead, which is per player and survives a restart but not a world
    reset.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

from .api import Edition
from .content import BlockDef, Content, EntityDef, ItemDef, RecipeDef
from .diagnostics import Category, DiagnosticBag
from .java_backend import BackendResult
from .luaparse import (
    Assign,
    Call,
    Chunk,
    Comparison,
    ExprStat,
    Function,
    FunctionBody,
    If,
    Index,
    LogicalOp,
    Name,
    Node,
    Number,
    String,
)
from . import bedrock_geometry


#: The namespace Luanti uses when the pack does not specify one.
DEFAULT_MOD_NAME = "luacraft"


@dataclass
class LuantiBackend:
    """Compiles Lua into a Luanti mod."""

    namespace: str = DEFAULT_MOD_NAME
    mod_name: str = DEFAULT_MOD_NAME
    description: str = "Generated by LuaCraft"
    #: OBJ models keyed by model name, produced by the converter.
    models: dict[str, str] = field(default_factory=dict)
    edition = Edition.LUANTI

    def __post_init__(self) -> None:
        self.diagnostics = DiagnosticBag()
        self._lines: list[str] = []
        self._counter = 0
        #: Name of the loop variable that holds the current player.
        self._player_binding: str | None = None
        #: Name of the loop variable that holds the current entity.
        self._entity_binding: str | None = None
        #: Identifier prefix used for the content that is registered.
        self._content_prefix = self.mod_name
        #: Line of the declaration currently being rendered, used to place
        #: the diagnostics at the right spot.
        self._content_line = 0

    # -- public -----------------------------------------------------------

    def compile(
        self, chunk: Chunk, content: Content | None = None
    ) -> BackendResult:
        """Compile a parsed chunk into a Luanti mod."""
        self._lines = []
        self._counter = 0

        if content is not None:
            self._emit_content(content)

        for statement in chunk.body:
            self._emit_statement(statement, self._lines)

        result = BackendResult(edition=Edition.LUANTI)
        result.add("init.lua", self._script())
        result.add("mod.conf", self._mod_conf())
        if content is not None:
            for path, body in self._texture_notes(content).items():
                result.add(path, body)
            for path, body in self._model_files(content).items():
                result.add(path, body)
        return result

    # -- files ------------------------------------------------------------

    def _mod_conf(self) -> str:
        return (
            f"name = {self.mod_name}\n"
            f"description = {self.description}\n"
            f"title = {self.mod_name}\n"
        )

    def _script(self) -> str:
        header = [
            "-- Generated by LuaCraft.",
            "-- This mod is free software; see the project README for details.",
            "",
            "local S = core",
            "",
        ]
        body = "\n".join(self._lines)
        if not body:
            body = "-- No logic was declared."
        return "\n".join(header) + body + "\n"

    # -- content ----------------------------------------------------------

    def _emit_content(self, content: Content) -> None:
        """Emit the registrations for the declared content.

        Items become craft items, blocks become nodes, recipes become
        crafting recipes, and entities become real Luanti entities with a
        mesh, a collision box, health and a small self contained AI.  Luanti
        merges a node and its item form, so a block does not need a separate
        item registration.
        """
        entity_ids = {entity.identifier for entity in content.entities.values()}
        for item in content.items.values():
            if item.fallback_for and item.fallback_for in entity_ids:
                # The target has real entity support, so the species card is
                # redundant.  It stays for Java and Bedrock, which do not.
                continue
            self._content_line = item.line
            self._lines.extend(self._render_item(item))
        for block in content.blocks.values():
            self._content_line = block.line
            self._lines.extend(self._render_block(block))
        for recipe in content.recipes.values():
            self._content_line = recipe.line
            self._lines.extend(self._render_recipe(recipe))
        if content.entities:
            self._lines.append(_ENTITY_HELPERS)
        for entity in content.entities.values():
            self._content_line = entity.line
            self._lines.extend(self._render_entity(entity))
        if content.items or content.blocks or content.recipes or content.entities:
            self._lines.append("")

    def _texture_notes(self, content: Content) -> dict[str, str]:
        """Tell the author which textures the mod expects to find."""
        textures: list[str] = []
        for item in content.items.values():
            if item.texture:
                textures.append(item.texture)
        for block in content.blocks.values():
            if block.texture:
                textures.append(block.texture)
        for entity in content.entities.values():
            textures.append(entity.texture or entity.model or entity.name)
        if not textures:
            return {}
        return {
            "textures/README.txt": (
                "Place the textures of this mod here.\n\n"
                "Expected files:\n"
                + "\n".join(f"  {name}.png" for name in sorted(set(textures)))
                + "\n"
            )
        }

    def _model_files(self, content: Content) -> dict[str, str]:
        """Write one OBJ per entity, or a generated box when none was given."""
        files: dict[str, str] = {}
        for entity in content.entities.values():
            model = _safe_name(entity.model or entity.name)
            path = f"models/{model}.obj"
            if path in files:
                continue
            obj = self.models.get(entity.model or entity.name)
            if obj is None:
                obj = self.models.get(model)
            if obj is None:
                geometry = bedrock_geometry.placeholder_geometry(
                    entity.width, entity.height, name=model
                )
                obj = bedrock_geometry.to_obj(geometry, name=model)
                if entity.model:
                    self.diagnostics.warn(
                        Category.PARTIAL_SUPPORT,
                        (
                            f"no geometry was supplied for {entity.identifier}; "
                            "Luanti gets a generated box instead of the original "
                            "Bedrock model"
                        ),
                        entity.line,
                        symbol=entity.identifier,
                        edition="luanti",
                        hint=(
                            "convert the pack with tools/convert_bedrock.py or "
                            "pass --model-dir"
                        ),
                    )
            files[path] = obj
        if files:
            files["models/README.txt"] = (
                "OBJ models generated from Bedrock geometry, 16 units = 1 block.\n"
                "They face +Z, which is the direction a Luanti entity uses at yaw 0.\n"
            )
        return files

    def _render_entity(self, entity: EntityDef) -> list[str]:
        identifier = self._identifier(entity.identifier)
        model = _safe_name(entity.model or entity.name)
        texture = entity.texture or entity.model or entity.name
        half_width = entity.width / 2.0
        health = entity.health or 10.0
        speed = (entity.movement_speed or 0.2) * 5.0
        lines: list[str] = [f"-- Entity: {identifier}"]

        if entity.unsupported:
            self.diagnostics.warn(
                Category.PARTIAL_SUPPORT,
                (
                    f"{entity.identifier}: these Bedrock behaviours have no "
                    "exact Luanti equivalent and were approximated: "
                    + ", ".join(sorted(entity.unsupported))
                ),
                entity.line,
                symbol=entity.identifier,
                edition="luanti",
                hint="review the generated AI in init.lua and adjust it by hand",
            )

        lines.append(f"S.register_entity({_lua_string(identifier)}, {{")
        lines.append("    initial_properties = {")
        lines.append("        physical = true,")
        lines.append("        collide_with_objects = true,")
        lines.append(
            f"        collisionbox = {{"
            f"{-half_width:.4f}, 0.0, {-half_width:.4f}, "
            f"{half_width:.4f}, {entity.height:.4f}, {half_width:.4f}}},"
        )
        lines.append('        visual = "mesh",')
        lines.append(f"        mesh = {_lua_string(f'models/{model}.obj')},")
        lines.append(f"        textures = {{{_lua_string(f'{texture}.png')}}},")
        lines.append("        visual_size = {x = 1, y = 1, z = 1},")
        lines.append(f"        hp_max = {_number(health)},")
        lines.append("        makes_footstep_sound = true,")
        lines.append("        stepheight = 0.6,")
        lines.append("    },")
        lines.append(f"    _lc_name = {_lua_string(entity.display_name or entity.name)},")
        lines.append(f"    _lc_speed = {_number(speed)},")
        lines.append(f"    _lc_hostile = {'true' if entity.hostile else 'false'},")
        lines.append(
            f"    _lc_damage = {_number(max(1.0, (entity.health or 10.0) / 10.0))},"
        )
        if entity.spawnable is not False:
            lines.append("    _lc_spawnable = true,")
        if entity.tameable:
            tame_items = ", ".join(
                _lua_string(self._identifier(str(item)))
                for item in entity.tameable.get("tame_items", [])
            )
            lines.append(
                "    _lc_tame = {"
                f"chance = {_number(entity.tameable.get('probability', 1.0))}, "
                f"items = {{{tame_items}}},"
                "},"
            )
        drops = ", ".join(
            "{item = "
            + _lua_string(self._identifier(str(drop["item"])))
            + f", min = {int(drop.get('min', 1))}, "
            + f"max = {int(drop.get('max', 1))}, "
            + f"chance = {_number(float(drop.get('chance', 1.0)))} }}"
            for drop in entity.drops
        )
        lines.append(f"    _lc_drops = {{{drops}}},")
        lines.append("    on_activate = function(self, staticdata, dtime_s)")
        lines.append("        self._lc_timer = 0")
        lines.append("        self._lc_attack = 0")
        lines.append("        self._lc_yaw = math.random() * math.pi * 2")
        lines.append("        self._lc_tamed = false")
        lines.append("        self._lc_owner = nil")
        lines.append("        self.object:set_armor_groups({fleshy = 100})")
        lines.append('        if staticdata and staticdata ~= "" then')
        lines.append('            self._lc_tamed = staticdata == "tamed"')
        lines.append("        end")
        lines.append("    end,")
        lines.append("    get_staticdata = function(self)")
        lines.append('        return self._lc_tamed and "tamed" or ""')
        lines.append("    end,")
        lines.append("    on_step = function(self, dtime, moveresult)")
        lines.append("        lc_entity_step(self, dtime, moveresult)")
        lines.append("    end,")
        lines.append(
            "    on_punch = function(self, puncher, time_from_last_punch, "
            "tool_capabilities, dir)"
        )
        lines.append("        lc_entity_punch(self, puncher, tool_capabilities)")
        lines.append("    end,")
        lines.append("    on_death = function(self, killer)")
        lines.append("        lc_entity_die(self)")
        lines.append("    end,")
        if entity.tameable:
            lines.append("    on_rightclick = function(self, clicker)")
            lines.append("        lc_entity_tame(self, clicker)")
            lines.append("    end,")
        lines.append("})")

        # A chat command is the reliable way to obtain an entity: Luanti has
        # no spawn eggs.  The ABM below only makes it appear naturally.
        command = f"spawn_{_safe_name(entity.identifier.split(':', 1)[-1])}"
        lines.append(f"S.register_chatcommand({_lua_string(command)}, {{")
        lines.append(
            "    description = "
            + _lua_string("Spawn " + (entity.display_name or entity.name))
            + ","
        )
        lines.append("    func = function(name)")
        lines.append("        local player = S.get_player_by_name(name)")
        lines.append('        if not player then return false, "no player" end')
        lines.append("        local pos = player:get_pos()")
        lines.append("        pos.y = pos.y + 1")
        lines.append(f"        S.add_entity(pos, {_lua_string(identifier)})")
        lines.append(
            "        return true, "
            + _lua_string("Spawned " + (entity.display_name or entity.name))
        )
        lines.append("    end,")
        lines.append("})")

        if entity.spawnable is not False:
            lines.append("S.register_abm({")
            lines.append(
                f"    label = {_lua_string('LuaCraft spawn ' + entity.identifier)},"
            )
            lines.append('    nodenames = {"group:soil"},')
            lines.append('    neighbors = {"air"},')
            lines.append("    interval = 30,")
            lines.append("    chance = 12000,")
            lines.append("    action = function(pos, node)")
            lines.append(
                "        if #S.get_objects_inside_radius(pos, 32) > 12 then return end"
            )
            lines.append("        pos.y = pos.y + 1")
            lines.append(f"        S.add_entity(pos, {_lua_string(identifier)})")
            lines.append("    end,")
            lines.append("})")
        lines.append("")
        return lines

    def _identifier(self, identifier: str) -> str:
        """Rewrite an identifier so its namespace matches the mod name.

        Identifiers from another game are kept as they are.  ``minecraft:``
        items do not exist in Luanti, but rewriting them to the mod name
        would be just as wrong: the author has to pick the equivalent item
        of the game they are targeting, which is usually ``default:``.
        """
        if ":" in identifier:
            namespace, _, name = identifier.partition(":")
            if namespace == self.mod_name:
                return identifier
            if namespace == "minecraft":
                # Leave it alone and let the author map it, but say so.
                self.diagnostics.warn(
                    Category.PARTIAL_SUPPORT,
                    (
                        f"{identifier} does not exist in Luanti. Luanti uses "
                        f"its own item names, usually in the 'default' "
                        f"namespace."
                    ),
                    self._content_line,
                    symbol=identifier,
                    edition="luanti",
                    hint=(
                        "use the equivalent item of the target game, for "
                        "example default:stick"
                    ),
                )
                return identifier
            return f"{self.mod_name}:{name}"
        return f"{self.mod_name}:{identifier}"

    def _render_item(self, item: ItemDef) -> list[str]:
        identifier = self._identifier(item.identifier)
        fields: list[str] = [f"description = {_lua_string(item.display_name or item.name)}"]
        if item.max_stack is not None:
            fields.append(f"stack_max = {item.max_stack}")
        if item.texture:
            fields.append(f"inventory_image = {_lua_string(item.texture)}")
        if item.hand_equipped:
            fields.append(" wieldable = true")
        if item.glint:
            fields.append(" groups = { luacraft_glint = 1 }")
        body = ", ".join(fields)
        return [
            f"S.register_craftitem({_lua_string(identifier)}, {{ {body} }})",
            f"S.add_to_creative_inventory({_lua_string(identifier)})",
        ]

    def _render_block(self, block: BlockDef) -> list[str]:
        identifier = self._identifier(block.identifier)
        fields: list[str] = [
            f"description = {_lua_string(block.name)}",
            f"tiles = {{ {_lua_string(block.texture or block.name)} }}",
        ]
        if block.hardness is not None:
            fields.append(f"hardness = {block.hardness}")
        if block.light_emission is not None:
            fields.append(f"light_source = {block.light_emission}")
        if block.map_color:
            fields.append(f"color = {_lua_string(block.map_color)}")
        body = ", ".join(fields)
        return [
            f"S.register_node({_lua_string(identifier)}, {{ {body} }})",
            f"S.add_to_creative_inventory({_lua_string(identifier)})",
        ]

    def _render_recipe(self, recipe: RecipeDef) -> list[str]:
        output = self._identifier(recipe.result)
        if recipe.count != 1:
            output = f"{output} {recipe.count}"

        if recipe.type == "shaped":
            matrix = self._recipe_matrix(recipe)
            rows = ", ".join(
                "{ " + ", ".join(_lua_string(cell) for cell in row) + " }"
                for row in matrix
            )
            return [
                "S.register_craft({",
                '    type = "shaped",',
                f"    output = {_lua_string(output)},",
                f"    recipe = {{ {rows} }},",
                "})",
            ]

        ingredients = ", ".join(
            _lua_string(self._identifier(item)) for item in recipe.ingredients
        )
        return [
            "S.register_craft({",
            '    type = "shapeless",',
            f"    output = {_lua_string(output)},",
            f"    recipe = {{ {ingredients} }},",
            "})",
        ]

    def _recipe_matrix(self, recipe: RecipeDef) -> list[list[str]]:
        """Turn a pattern and a key into Luanti's two dimensional grid."""
        matrix: list[list[str]] = []
        for row in recipe.pattern:
            cells: list[str] = []
            for character in row:
                if character == " ":
                    cells.append("")
                    continue
                item = recipe.key.get(character)
                if item is None:
                    # A character with no entry is an empty slot, which is
                    # what Luanti expects for a gap in the shape.
                    cells.append("")
                    continue
                cells.append(self._identifier(item))
            matrix.append(cells)
        return matrix

    # -- statements -------------------------------------------------------

    def _emit_statement(self, node: Node, out: list[str]) -> None:
        if isinstance(node, ExprStat):
            self._emit_call(node.expression, out)
            return
        if isinstance(node, If):
            self._emit_if(node, out)
            return
        if isinstance(node, Assign):
            target = node.targets[0]
            if isinstance(target, Index):
                return
            value = node.values[0] if node.values else None
            if isinstance(value, Call):
                self._emit_call(value, out)
            return
        return

    def _emit_if(self, node: If, out: list[str]) -> None:
        """Emit an `if` statement.

        The block is emitted on a single line so that it can be inlined into
        a ``for`` loop without breaking the Lua syntax.  The else branch is
        attached to the last if of the chain, which is how Lua reads it.
        """
        parts: list[str] = []
        for condition, body in node.branches:
            expression = self._condition_expression(condition)
            if expression is None:
                continue
            inner = "; ".join(self._body_lines(body))
            parts.append(f"if {expression} then {inner} end")

        if not parts:
            if node.else_body:
                inner = "; ".join(self._body_lines(node.else_body))
                out.append(inner)
            return

        if node.else_body:
            inner = "; ".join(self._body_lines(node.else_body))
            parts.append(f"else {inner} end")

        out.append(" ".join(parts))

    def _body_lines(self, body: list[Node]) -> list[str]:
        buffer: list[str] = []
        for statement in body:
            self._emit_statement(statement, buffer)
        return buffer

    def _condition_expression(self, condition: Node) -> str | None:
        """Translate a Lua condition into a Luanti expression."""
        comparison: Comparison | None = None
        if isinstance(condition, Comparison):
            comparison = condition
        elif isinstance(condition, LogicalOp) and condition.op == "and":
            for part in (condition.left, condition.right):
                if isinstance(part, Comparison):
                    comparison = part
                    break
        if comparison is None:
            return None
        if comparison.op not in (">=", ">", "<=", "<", "==", "~="):
            return None
        if not isinstance(comparison.left, Call):
            return None
        if not isinstance(comparison.left.func, Name):
            return None
        if comparison.left.func.identifier != "score":
            return None
        args = comparison.left.args
        if len(args) < 2:
            return None
        player = _lua_player_object(args[0], self._player_binding)
        objective = _plain(args[1])
        operator = {
            ">=": ">=", ">": ">", "<=": "<=", "<": "<",
            "==": "==", "~=": "~=",
        }[comparison.op]
        value = _literal(comparison.right)
        return (
            f"{player}:get_meta():get_int({_lua_string(objective)}) "
            f"{operator} {value}"
        )

    def _emit_call(self, node: Node, out: list[str]) -> None:
        if not isinstance(node, Call):
            return
        if node.method or not isinstance(node.func, Name):
            return
        name = node.func.identifier

        if name == "onTick":
            out.append("S.register_globalstep(function(dtime)")
            out.extend(f"    {line}" for line in self._hook_body(node))
            out.append("end)")
            return
        if name in ("onJoin", "onLoad"):
            out.append("S.register_on_joinplayer(function(player)")
            out.extend(f"    {line}" for line in self._hook_body(node))
            out.append("end)")
            return
        if name == "onLuantiOnly":
            out.extend(self._hook_body(node))
            return
        if name in ("onJavaOnly", "onBedrockOnly"):
            # Dropped from the Luanti build.
            return

        expression = self._expression_for(name, node)
        if expression:
            out.append(expression)

    def _hook_body(self, node: Call) -> list[str]:
        callback = node.args[0] if node.args else None
        if not isinstance(callback, Function):
            return []
        return self._body_lines(callback.body.body)

    # -- expressions ------------------------------------------------------

    def _expression_for(self, name: str, node: Call) -> str:
        args = node.args

        def arg(index: int, default: str = '""') -> str:
            """Fetch an argument as a Lua literal, ready to be pasted."""
            if index < len(args):
                return _lua_literal(args[index])
            return default

        def text(index: int, default: str = "") -> str:
            """Fetch an argument as the plain text it holds."""
            if index < len(args):
                return _literal(args[index])
            return default

        def player_arg(index: int) -> str:
            """The player as an object reference, for the method calls."""
            if index < len(args):
                return _lua_player_object(args[index], self._player_binding)
            return "player"

        def player_name(index: int) -> str:
            """The player as a name, for the chat functions."""
            if index < len(args):
                return _lua_player_name(args[index], self._player_binding)
            return '"player"'

        if name == "say":
            return f"S.chat_send_all({arg(0)})"
        if name == "message":
            return f"S.chat_send_player({player_name(0)}, {arg(1)})"
        if name == "give":
            item = self._identifier(text(1))
            count = arg(2, "1")
            return (
                f"{player_arg(0)}:get_inventory():add_item("
                f"ItemStack({_lua_string(item)} .. \" \" .. {count}))"
            )
        if name == "clear":
            if len(args) > 1:
                item = self._identifier(text(1))
                return (
                    f"{player_arg(0)}:get_inventory():remove_item("
                    f"ItemStack({_lua_string(item)}))"
                )
            return f"{player_arg(0)}:get_inventory():clear()"
        if name == "score":
            objective = text(1)
            if len(args) == 2:
                return (
                    f"{player_arg(0)}:get_meta():get_int("
                    f"{_lua_string(objective)})"
                )
            operation = text(2)
            value = arg(3, "1")
            if operation in ("add", "plus"):
                return (
                    f"{player_arg(0)}:get_meta():set_int("
                    f"{_lua_string(objective)}, "
                    f"{player_arg(0)}:get_meta():get_int({_lua_string(objective)}) "
                    f"+ {value})"
                )
            if operation in ("remove", "subtract", "minus"):
                return (
                    f"{player_arg(0)}:get_meta():set_int("
                    f"{_lua_string(objective)}, "
                    f"{player_arg(0)}:get_meta():get_int({_lua_string(objective)}) "
                    f"- {value})"
                )
            return (
                f"{player_arg(0)}:get_meta():set_int("
                f"{_lua_string(objective)}, {value})"
            )
        if name == "addObjective":
            # Luanti keeps scores in the player metadata, so there is nothing
            # to declare.
            return ""
        if name == "forEachPlayer":
            saved = self._player_binding
            self._player_binding = "player"
            try:
                body = self._callback_body(node.args[0] if node.args else None)
            finally:
                self._player_binding = saved
            return f"for _, player in ipairs(S.get_connected_players()) do {body} end"
        if name == "forEachEntity":
            saved = self._entity_binding
            self._entity_binding = "entity"
            try:
                body = self._callback_body(
                    node.args[1] if len(node.args) > 1 else None
                )
            finally:
                self._entity_binding = saved
            entity_type = text(0)
            return (
                "for _, entity in ipairs(S.get_objects_inside_radius("
                "vector.new(0, 0, 0), 1000)) do "
                f"if entity:get_luaentity() and entity:get_luaentity().name "
                f"== {_lua_string(entity_type)} then {body} end end"
            )
        if name == "setblock":
            block = text(3)
            return (
                f"S.set_node(vector.new({arg(0)}, {arg(1)}, {arg(2)}), "
                f"{_lua_string(block)})"
            )
        if name == "getBlock":
            return (
                f"S.get_node(vector.new({arg(0)}, {arg(1)}, {arg(2)})).name"
            )
        if name == "teleport":
            target = player_arg(0)
            return (
                f"{target}:set_pos(vector.new({arg(1)}, {arg(2)}, {arg(3)}))"
            )
        if name == "setDynamicProperty":
            return (
                f"{player_arg(0)}:get_meta():set_string("
                f"{arg(1)}, {arg(2)})"
            )
        if name == "getDynamicProperty":
            return f"{player_arg(0)}:get_meta():get_string({arg(1)})"
        if name == "playSound":
            # Luanti has no server side sound API, so the sound is announced
            # through the chat and expanded client side.
            if len(args) > 1:
                return f"S.chat_send_player({player_name(1)}, {arg(0)})"
            return f"S.chat_send_all({arg(0)})"
        if name == "effect":
            return "-- effect() has no Luanti equivalent"
        if name == "nbt":
            return "-- nbt() has no Luanti equivalent"
        if name == "runCommand":
            return (
                f"S.register_chatcommand({_lua_string(text(0))}, "
                "{ description = \"LuaCraft command\", func = function() end })"
            )
        return ""

    def _callback_body(self, callback: Node | None) -> str:
        """Render a callback function as the body of a Lua block.

        The lines are joined with semicolons so that a multi line block
        stays valid Lua when it is inlined into a ``for`` loop.
        """
        if not isinstance(callback, Function):
            return "-- empty"
        lines = self._body_lines(callback.body.body)
        if not lines:
            return "-- empty"
        return "; ".join(lines)


