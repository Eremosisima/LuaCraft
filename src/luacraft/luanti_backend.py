def _lua_string(value: str) -> str:
    """Render a string as a Lua literal."""
    escaped = (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\t", "\\t")
    )
    return f'"{escaped}"'


def _lua_literal(node: Node) -> str:
    """Render a Lua literal as a Luanti literal, ready to be pasted."""
    if isinstance(node, String):
        return _lua_string(node.value)
    if isinstance(node, Number):
        return str(node.value)
    if isinstance(node, Name):
        return _lua_string(node.identifier)
    return '""'


def _literal(node: Node) -> str:
    """Render a Lua literal as the plain string it holds."""
    if isinstance(node, String):
        return node.value
    if isinstance(node, Number):
        return str(node.value)
    if isinstance(node, Name):
        return node.identifier
    return ""


def _plain(node: Node) -> str:
    if isinstance(node, String):
        return node.value
    if isinstance(node, Name):
        return node.identifier
    if isinstance(node, Number):
        return str(node.value)
    return ""


def _lua_player_name(node: Node, binding: str | None = None) -> str:
    """Render a player reference as a player name, for the chat functions."""
    if isinstance(node, Name):
        if binding and node.identifier in ("player", "self", "s", "target"):
            return binding
        return f'"{node.identifier}"'
    return '"player"'


def _lua_player_object(node: Node, binding: str | None = None) -> str:
    """Render a player reference as an object reference, for the methods."""
    if isinstance(node, Name):
        if binding and node.identifier in ("player", "self", "s", "target"):
            return binding
        return f'S.get_player_by_name("{node.identifier}")'
    return "player"


