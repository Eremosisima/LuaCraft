"""Run a generated Luanti mod inside a real Luanti server.

The tool installs the mod archive into the local Luanti user directory,
creates a throwaway world, adds a worldmod that inspects the Lua API and
spawns one entity, and runs ``luanti --server`` headless.  It then parses the
log and fails when a registration, model, texture or entity step is missing.

This is a development validator, not part of the compiler.  It only touches
the user's own ``mods`` and ``worlds`` directories.
"""

from __future__ import annotations

import argparse
import os
import re
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path

PROBE_MOD = "zz_luacraft_runtime_probe"

PROBE_TEMPLATE = """\
-- Generated by tools/validate_luanti_runtime.py.
local MOD = {mod!r}
local ENTITY = {entity!r}
local ITEM = {item!r}

local function log(message)
    core.log("action", "[luacraft-runtime] " .. tostring(message))
end

local function file_size(path)
    local handle = io.open(path, "rb")
    if not handle then return -1 end
    local size = handle:seek("end")
    handle:close()
    return size
end

local failed = false
local function check(label, condition, detail)
    log(label .. ": " .. tostring(condition) .. (detail and (" " .. detail) or ""))
    if not condition then failed = true end
end

core.after(600, function()
    log("timeout, shutting down")
    core.request_shutdown()
end)

core.after(2, function()
    local ok, err = pcall(function()
        local total = 0
        for _ in pairs(core.registered_entities) do total = total + 1 end
        log("engine entities: " .. total)

        local definition = core.registered_entities[ENTITY]
        check("entity registered", definition ~= nil, ENTITY)
        if definition then
            local props = definition.initial_properties or {{}}
            local name = ENTITY:match(":(.+)$") or ENTITY
            check("visual", props.visual == "mesh", tostring(props.visual))
            check("mesh", type(props.mesh) == "string" and #props.mesh > 0,
                tostring(props.mesh))
            check("mesh media name", props.mesh == name .. "_model.obj",
                tostring(props.mesh))
            check("hp_max", (props.hp_max or 0) > 0, tostring(props.hp_max))
            check("collisionbox", #(props.collisionbox or {{}}) == 6)
        end

        if ITEM ~= "" then
            local item = core.registered_items[ITEM]
            check("item registered", item ~= nil, ITEM)
            if item then
                check("inventory image", (item.inventory_image or "") ~= "",
                    tostring(item.inventory_image))
            end
        end

        local modpath = core.get_modpath(MOD)
        check("mod path", modpath ~= nil, tostring(modpath))
        if modpath then
            local name = ENTITY:match(":(.+)$") or ENTITY
            local mesh = modpath .. "/models/" .. name .. "_model.obj"
            local texture = modpath .. "/textures/" .. name .. ".png"
            check("model file", file_size(mesh) > 0, tostring(file_size(mesh)))
            check("texture file", file_size(texture) > 0,
                tostring(file_size(texture)))
        end

        core.emerge_area({{x = 0, y = 0, z = 0}}, {{x = 15, y = 31, z = 15}},
            function(blockpos, action, remaining)
                if remaining ~= 0 then return end
                core.after(0.2, function()
                    local ground
                    for y = 30, -5, -1 do
                        local node = core.get_node({{x = 8, y = y, z = 8}})
                        if node and node.name ~= "air" and node.name ~= "ignore" then
                            ground = y
                            break
                        end
                    end
                    local position = {{x = 8.5, y = (ground or 0) + 2, z = 8.5}}
                    core.forceload_block(position, true)
                    local object = core.add_entity(position, ENTITY)
                    check("entity created", object ~= nil and object:get_pos() ~= nil)
                    core.after(1.5, function()
                        local found = false
                        for _, candidate in ipairs(
                            core.get_objects_inside_radius(position, 8)
                        ) do
                            local entity = candidate:get_luaentity()
                            if entity and entity.name == ENTITY then
                                found = true
                                local pos = candidate:get_pos()
                                log(string.format(
                                    "entity stepped at %.2f %.2f %.2f hp=%s",
                                    pos.x, pos.y, pos.z,
                                    tostring(candidate:get_hp())
                                ))
                            end
                        end
                        check("entity survives a step", found)
                        core.forceload_block(position, false)
                        log("RESULT " .. (failed and "FAIL" or "PASS"))
                        core.after(0.5, function() core.request_shutdown() end)
                    end)
                end)
            end)
    end)
    if not ok then
        log("probe error: " .. tostring(err))
        log("RESULT FAIL")
        core.request_shutdown()
    end
end)
"""


def _user_dir() -> Path:
    appdata = os.environ.get("APPDATA")
    if not appdata:
        raise SystemExit("APPDATA is not set; this validator targets Windows")
    return Path(appdata) / "minetest"


def _install_mod(archive: Path, mod_name: str, mods_dir: Path) -> None:
    target = mods_dir / mod_name
    if target.exists():
        shutil.rmtree(target)
    with zipfile.ZipFile(archive) as zipped:
        zipped.extractall(mods_dir)
    extracted = mods_dir / mod_name
    if not extracted.is_dir():
        raise SystemExit(f"{archive} does not contain a {mod_name}/ folder")


def _write_world(
    world: Path, mod_name: str, entity: str, item: str
) -> None:
    if world.exists():
        shutil.rmtree(world)
    probe = world / "worldmods" / PROBE_MOD
    probe.mkdir(parents=True)
    (world / "world.mt").write_text(
        "\n".join(
            [
                "gameid = mineclonia",
                f"world_name = {world.name}",
                "backend = sqlite3",
                "player_backend = sqlite3",
                "auth_backend = sqlite3",
                "mod_storage_backend = sqlite3",
                f"load_mod_{mod_name} = true",
                "",
            ]
        ),
        encoding="utf-8",
    )
    (probe / "init.lua").write_text(
        PROBE_TEMPLATE.format(mod=mod_name, entity=entity, item=item),
        encoding="utf-8",
    )


def _run(exe: Path, world: Path, logfile: Path) -> int:
    if logfile.exists():
        logfile.unlink()
    completed = subprocess.run(
        [
            str(exe),
            "--server",
            "--world",
            str(world),
            "--gameid",
            "mineclonia",
            "--logfile",
            str(logfile),
        ],
        cwd=str(exe.parent),
        capture_output=True,
        text=True,
        timeout=600,
    )
    return completed.returncode


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("archive", type=Path, help="the *-luanti.zip to install")
    parser.add_argument("--mod", required=True, help="mod name inside the zip")
    parser.add_argument("--entity", required=True, help="entity to spawn")
    parser.add_argument("--item", default="", help="item to check")
    parser.add_argument(
        "--luanti",
        type=Path,
        default=Path(
            r"C:\Users\PC\AppData\Local\luanti\5.17.0\bin\luanti.exe"
        ),
        help="luanti executable",
    )
    parser.add_argument(
        "--world-name", default=None, help="world directory name"
    )
    args = parser.parse_args(argv)

    if not args.archive.exists():
        raise SystemExit(f"{args.archive} does not exist")

    user_dir = _user_dir()
    mods_dir = user_dir / "mods"
    worlds_dir = user_dir / "worlds"
    mods_dir.mkdir(parents=True, exist_ok=True)
    worlds_dir.mkdir(parents=True, exist_ok=True)

    world_name = args.world_name or f"luacraft_{args.archive.stem}_probe"
    world = worlds_dir / world_name
    logfile = Path(os.environ.get("TEMP", ".")) / f"{world_name}.log"

    _install_mod(args.archive, args.mod, mods_dir)
    _write_world(world, args.mod, args.entity, args.item)
    code = _run(args.luanti, world, logfile)
    text = logfile.read_text(encoding="utf-8", errors="replace") if logfile.exists() else ""

    lines = [
        line.split("]: ", 1)[-1]
        for line in text.splitlines()
        if "[luacraft-runtime]" in line
    ]
    for line in lines:
        print("  " + line)

    errors = [
        line
        for line in text.splitlines()
        if "ERROR" in line or "ModError" in line or "stack traceback" in line
    ]
    passed = (
        any(line.rstrip().endswith("RESULT PASS") for line in lines)
        and not errors
    )
    print(f"{args.mod}: exit={code} result={'PASS' if passed else 'FAIL'} log={logfile}")
    if errors:
        for line in errors[:20]:
            print("  " + line)
    return 0 if passed else 1


if __name__ == "__main__":
    sys.exit(main())
