"""Tests for the Bedrock geometry reader and its two exporters."""

from __future__ import annotations

import math

from luacraft import bedrock_geometry


def _geometry() -> dict:
    return {
        "format_version": "1.16.0",
        "minecraft:geometry": [
            {
                "description": {
                    "identifier": "geometry.test",
                    "texture_width": 64,
                    "texture_height": 32,
                    "visible_bounds_width": 2,
                    "visible_bounds_height": 3,
                },
                "bones": [
                    {
                        "name": "body",
                        "pivot": [0, 8, 0],
                        "cubes": [
                            {
                                "origin": [-4, 0, -4],
                                "size": [8, 16, 8],
                                "uv": [0, 0],
                            }
                        ],
                    },
                    {
                        "name": "head",
                        "parent": "body",
                        "pivot": [0, 16, 0],
                        "rotation": [0, 45, 0],
                        "cubes": [
                            {
                                "origin": [-4, 16, -4],
                                "size": [8, 8, 8],
                                "uv": [0, 16],
                            }
                        ],
                    },
                ],
            }
        ],
    }


def test_parses_every_geometry_in_a_file() -> None:
    geometries = bedrock_geometry.parse_geometries(_geometry())
    assert len(geometries) == 1
    geometry = geometries[0]
    assert geometry.identifier == "geometry.test"
    assert geometry.texture_width == 64
    assert geometry.texture_height == 32
    assert [bone.name for bone in geometry.bones] == ["body", "head"]


def test_parse_geometry_returns_none_for_unrelated_json() -> None:
    assert bedrock_geometry.parse_geometry({"hello": "world"}) is None


def test_bounds_are_in_bedrock_units() -> None:
    geometry = bedrock_geometry.parse_geometry(_geometry())
    lower, upper = bedrock_geometry.bounds(geometry)
    assert lower[1] == 0
    assert upper[1] >= 24


def test_bounds_blocks_divides_by_16() -> None:
    geometry = bedrock_geometry.parse_geometry(_geometry())
    lower, upper = bedrock_geometry.bounds_blocks(geometry)
    assert math.isclose(lower[1], 0.0)
    assert math.isclose(upper[1], 1.5, rel_tol=0.2)


def test_obj_has_vertices_uvs_normals_and_triangles() -> None:
    geometry = bedrock_geometry.parse_geometry(_geometry())
    obj = bedrock_geometry.to_obj(geometry, name="test")
    assert obj.startswith("# Generated by LuaCraft")
    assert "\nv " in obj
    assert "\nvt " in obj
    assert "\nvn " in obj
    assert "\nf " in obj
    # Two cubes, six faces each, two triangles per face.
    assert obj.count("\nf ") == 24


def test_obj_flips_z_so_the_model_faces_luanti_yaw_zero() -> None:
    geometry = bedrock_geometry.parse_geometry(_geometry())
    obj = bedrock_geometry.to_obj(geometry, name="test")
    vertices = [line.split()[1:] for line in obj.splitlines() if line.startswith("v ")]
    assert vertices
    # A cube centred on X and Z must stay centred after the 180 degree turn.
    xs = [float(vertex[0]) for vertex in vertices]
    assert math.isclose(min(xs), -max(xs), abs_tol=1e-6)


def test_blockymodel_nodes_keep_the_bone_hierarchy() -> None:
    geometry = bedrock_geometry.parse_geometry(_geometry())
    document = bedrock_geometry.to_blockymodel(geometry, name="Test")
    assert document["format"] == "character"
    assert document["lod"] == "auto"
    assert len(document["nodes"]) == 1
    root = document["nodes"][0]
    assert root["name"] == "body"
    assert any(child.get("name") == "head" for child in root["children"])


def test_blockymodel_has_per_face_texture_layout() -> None:
    geometry = bedrock_geometry.parse_geometry(_geometry())
    document = bedrock_geometry.to_blockymodel(geometry, name="Test")

    def find_shape(node):
        if "shape" in node and node["shape"].get("type") == "box":
            return node["shape"]
        for child in node.get("children", []):
            found = find_shape(child)
            if found:
                return found
        return None

    shape = find_shape(document["nodes"][0])
    assert shape is not None
    assert shape["type"] == "box"
    assert shape["textureLayout"]
    assert "up" in shape["textureLayout"]
    assert "offset" in shape["textureLayout"]["up"]


def test_blockymodel_quaternion_is_normalised() -> None:
    geometry = bedrock_geometry.parse_geometry(_geometry())
    document = bedrock_geometry.to_blockymodel(geometry, name="Test")
    orientation = document["nodes"][0]["children"][1]["orientation"]
    length = math.sqrt(
        orientation["x"] ** 2
        + orientation["y"] ** 2
        + orientation["z"] ** 2
        + orientation["w"] ** 2
    )
    assert math.isclose(length, 1.0, rel_tol=1e-5)


def test_placeholder_geometry_has_a_box() -> None:
    geometry = bedrock_geometry.placeholder_geometry(0.8, 1.9, name="fallback")
    assert geometry.bones
    assert geometry.bones[0].cubes
    obj = bedrock_geometry.to_obj(geometry)
    assert obj.count("\nf ") == 12
